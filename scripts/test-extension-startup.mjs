import assert from 'node:assert/strict'
import fs from 'node:fs'
const read = file => fs.readFileSync(new URL(`../${file}`, import.meta.url), 'utf8')
const main = read('src/main.ts')
assert.doesNotMatch(main, /await useAuthStore\(\)\.(upgradeLegacyExtensionSession|refreshSession)/, 'network authentication must not block mounting')
assert.match(read('src/router/permission.ts'), /!cachedExtensionHome && authStore.authMode/)
const dashboard = read('src/views/extension/index.vue')
assert.match(dashboard, /await loadCachedSnapshot\(\)[\s\S]*requestAnimationFrame[\s\S]*await refreshBootstrap\(\)/)
assert.match(read('extension/newtab.html'), /prefers-color-scheme: dark/)
assert.match(read('src/components/common/ItemIcon/index.vue'), /getCachedIconImage\(source\)/)
assert.match(read('src/plugins/modalFocus.ts'), /flush: 'sync'/)
assert.match(read('src/api/sync.ts'), /timeout: 35000/)
const newtab = read('extension/newtab.html')
assert.ok(newtab.indexOf('<script src="./boot-wallpaper.js"></script>') < newtab.indexOf('</head>') && newtab.indexOf('boot-wallpaper.js') < newtab.indexOf('src/main.ts'), 'Saved wallpaper paints from <head>, before the application module graph')
assert.doesNotMatch(newtab, /<script type="module" src="\.\/boot-wallpaper/, 'The boot paint must stay a classic, unbundled script')
const bootScript = read('extension/boot-wallpaper.js')
const bootKey = read('src/runtime/extension.ts').match(/const BOOT_WALLPAPER_KEY = '([^']+)'/)?.[1]
assert.ok(bootKey && bootScript.includes(`localStorage.getItem('${bootKey}')`), 'Boot script and runtime share the mirror key')
assert.match(read('vite.config.mts'), /'boot-wallpaper\.js'\]/)
assert.match(read('extension/newtab.html'), /data-panel-runtime="extension"/)
assert.match(read('extension/newtab.html'), /\[data-boot-wallpaper\] \.loading-wrap \{ visibility: hidden; \}/)
assert.match(dashboard, /rememberBootWallpaper\(url, mask\)/)
console.log('Extension startup: cached-first paint, bounded authentication, icon read and focus safeguards passed')
